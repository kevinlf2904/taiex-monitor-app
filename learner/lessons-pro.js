// 模擬大盤的漲跌家數：漲的日子上漲家數多、跌的日子下跌家數多；最後三成故意讓家數變弱（指數還在漲，但漲的股票越來越少），用來教騰落背離
function withBreadth(D, seed = 1) {
  const r = mulberry32(seed * 13 + 7), tot = 950, n = D.length;
  return D.map((x, i) => {
    const ret = i ? x.c / D[i - 1].c - 1 : 0, late = Math.max(0, (i / n - 0.7) / 0.3);
    const share = Math.min(0.92, Math.max(0.08, 0.5 + 0.4 * Math.tanh(ret / 0.012) + (r() - 0.5) * 0.16 - 0.14 * late));
    const flat = Math.round(tot * (0.06 + r() * 0.04)), adv = Math.round((tot - flat) * share);
    return { ...x, adv, dec: tot - flat - adv };
  });
}
